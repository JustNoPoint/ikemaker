'use strict';
const assert=require('assert');
const triggers=require('../data/triggers.json');
const {signaturePositions,argumentSlots,argumentSlot,argumentSummary}=require('../src/trigger_argument_model');
const {filterEntry}=require('../src/catalog_capability_filter');
const {hoverModel}=require('../src/language_intelligence');
const {triggerSignatureHelp}=require('../src/language_providers');
const {triggerProjection}=require('../src/authoring_browser_model');

const env=triggers.find(entry=>entry.name==='EnvShakeVar'),slots=argumentSlots(env);
assert.deepStrictEqual(signaturePositions(env),['param_name']);
assert.strictEqual(slots.length,1,'four known values remain alternatives for one ordered argument');
assert.deepStrictEqual(slots[0].choices.map(choice=>choice.value),['time','freq','ampl','dir']);
assert.strictEqual(argumentSlot(env,0).name,'param_name');
assert.match(argumentSlot(env,0).choices.find(choice=>choice.value==='dir').meaning,/base shake direction/i);
assert.match(argumentSummary(env),/1\. param_name/);assert.match(argumentSummary(env),/time, freq, ampl, dir/);

const legacy={name:'Clamp',signature:'Clamp(value, min, max)',arguments:'value'};
assert.deepStrictEqual(argumentSlots(legacy).map(slot=>slot.name),['value','min','max'],'legacy prose is not inferred as choices and the signature remains positional authority');
assert(argumentSlots(legacy).every(slot=>slot.choices.length===0&&slot.allowExpression));
const gated={name:'Gated',signature:'Gated(mode)',argumentSlots:[{position:0,name:'mode',choices:[{value:'stable'},{value:'night',capabilityId:'test.nightly'}]}]};
assert.deepStrictEqual(argumentSlot(gated,0,{enabledCapabilities:[]}).choices.map(choice=>choice.value),['stable']);
assert.deepStrictEqual(argumentSlot(gated,0,{enabledCapabilities:['test.nightly']}).choices.map(choice=>choice.value),['stable','night']);
assert.deepStrictEqual(filterEntry(gated,{enabledCapabilities:[]}).argumentSlots[0].choices.map(choice=>choice.value),['stable'],'catalog projection cannot leak unavailable choices');
const hover=hoverModel({word:'EnvShakeVar',text:'trigger1 = EnvShakeVar(dir)',line:0,languageId:'ikemen-cns',experience:'learning',triggers:[env]});
assert.match(hover.explanation,/1\. param_name/);assert.match(hover.explanation,/time, freq, ampl, dir/,'hover reuses structured alternatives');
const signature=triggerSignatureHelp({name:'EnvShakeVar',activeParameter:0},[env]);
assert.match(signature.signatures[0].parameters[0].documentation,/dir — Stored base shake direction/,'signature help gives the active position its shared choice meaning');
const projected=triggerProjection([env]).items[0].children[0].children[0];
assert.match(projected.description,/1\. param_name/);assert.match(projected.description,/time, freq, ampl, dir/,'authoring browser reuses the same positional summary');
console.log('Trigger argument model preserves positions, structured alternatives, expression fallback and exact capabilities');
