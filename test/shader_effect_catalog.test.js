'use strict';

const assert=require('assert'),crypto=require('crypto');
const {createShaderProject,selectPreset,setSafeguard}=require('../src/shader_workshop_model');
const {EFFECTS,compileTrustedEffect}=require('../src/shader_effect_catalog');
const {classifySafeguards}=require('../src/shader_safeguard_policy');
let project=createShaderProject({id:'fixture',name:'Fixture',now:1});
const clean=compileTrustedEffect(project);
assert.strictEqual(clean.effectId,'passthrough');assert(clean.fragment.includes('sourceColor.a <= 0.0')&&clean.fragment.includes('color.a = sourceColor.a')&&clean.fragment.includes('clamp(color'));
assert.strictEqual(clean.sampler.min,'nearest');
assert(clean.fallback.vertex.includes('attribute vec2')&&clean.fallback.fragment.includes('texture2D(')&&clean.fallback.fragment.includes('gl_FragColor'));
assert.deepStrictEqual([...new Set(clean.policy.map(item=>item.status))],['enforced']);
project=selectPreset(project,'palette-tint',2);
assert.throws(()=>compileTrustedEffect(project),/Preserve palette colors/);
project=setSafeguard(project,'preservePaletteColors',false,3);project=setSafeguard(project,'preserveIndexedPaletteBehavior',false,4);
const tint=compileTrustedEffect(project,'palette-tint',{amount:9,tint:[2,-1,.5,1]});
assert.strictEqual(tint.parameters.amount,1);assert.deepStrictEqual(tint.parameters.tint,[1,0,.5,1]);
assert(!tint.fragment.includes('9')&&!tint.fragment.includes('undefined'));
assert.throws(()=>compileTrustedEffect({...project,mode:'code'}),/Only trusted preset/);
assert.throws(()=>compileTrustedEffect(project,'forged-effect'),/Unknown or untrusted/);
const hash=crypto.createHash('sha256').update(clean.vertex+'\0'+clean.fragment).digest('hex');
assert.strictEqual(hash,'72e23c220c5a7c6b196cf1d06fc8ecc37e09cbb91df1c2719cc5e110a77d7de7');
for(const effect of EFFECTS)assert(['passthrough','palette-tint','grayscale','hit-flash','pixelate'].includes(effect.id));
const statuses=classifySafeguards(project,EFFECTS.find(item=>item.id==='palette-tint'));
assert(statuses.some(item=>item.id==='preservePaletteColors'&&item.status==='advisory'));
let pixelate=createShaderProject({id:'pixelate',name:'Pixelate',now:1});pixelate=selectPreset(pixelate,'pixelate',2);
assert.throws(()=>compileTrustedEffect(pixelate),/Preserve palette colors/,'pixelation cannot claim exact per-pixel RGB preservation');
console.log('Trusted shader compiler is deterministic, parameter-bounded, and safeguard-gated');
