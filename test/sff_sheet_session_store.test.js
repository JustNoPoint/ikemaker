'use strict';

const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { indexedSourcePng } = require('../src/sff_reader');
const { sha256, gridProposal, extractIndexedGrid, analyzeIndexedComponents } = require('../src/sff_sheet_intake');
const { createStoredSession, openStoredSession, persistReviewAction, persistRectangleAdjustment, persistComponentAttachment, persistComponentDetachment, storedExtractedFrames, listStoredSessions } = require('../src/sff_sheet_session_store');

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ikemaker-sheet-session-'));
const colors = Array.from({ length: 256 }, (_, index) => [index, index, index, index ? 255 : 0]);
const source = indexedSourcePng(4, 2, Buffer.from([1, 1, 2, 2, 1, 1, 2, 2]), colors), sourceHash = sha256(source);
const proposal = gridProposal({ width: 4, height: 2, sourceHash }, { cellWidth: 2, cellHeight: 2 });
const extracted = extractIndexedGrid(source, proposal);
const componentAudit = analyzeIndexedComponents(source, { mode: 'alpha', proposal });
let stored = createStoredSession(fs, root, source, proposal, { sessionId: 'sheet-test', sourceName: 'sheet.png', firstNumericGroup: 100, intakeEvidence: { sourceHash, componentAudit }, extractedFrames: extracted });
assert(fs.existsSync(stored.location.source) && fs.existsSync(stored.location.document) && fs.existsSync(stored.location.lock));
assert.strictEqual(storedExtractedFrames(fs, stored).length, 2); assert(storedExtractedFrames(fs, stored).every(frame => fs.existsSync(frame.filename)));
assert.throws(() => openStoredSession(fs, root, 'sheet-test'), /already open/);
const secondComponent = componentAudit.components.find(component => component.frameIds.includes(proposal.frames[1].frameId));
assert.throws(() => persistComponentAttachment(fs, stored, [secondComponent.componentId], 'exclusive', 'weapon'), /Choose duplicated ownership/);
const beforeAttachmentHash = storedExtractedFrames(fs, stored)[0].byteHash;
stored = persistComponentAttachment(fs, stored, [secondComponent.componentId], 'duplicate', 'shared effect');
assert.strictEqual(stored.state.componentAttachments[0].ownership, 'duplicate');
assert.notStrictEqual(storedExtractedFrames(fs, stored)[0].byteHash, beforeAttachmentHash, 'attaching an audited floating part atomically regenerates the affected cached frame');
stored = persistComponentDetachment(fs, stored, [secondComponent.componentId]);
assert.strictEqual(stored.state.componentAttachments.length, 0);
const originalFrameHash = storedExtractedFrames(fs, stored)[0].byteHash;
stored = persistRectangleAdjustment(fs, stored, { x: 0, y: 0, width: 1, height: 2 });
assert.deepStrictEqual(stored.state.currentFrame.sourceRectangle, { x: 0, y: 0, width: 1, height: 2 });
assert.notStrictEqual(storedExtractedFrames(fs, stored)[0].byteHash, originalFrameHash, 'a corrected rectangle atomically replaces only its cached extracted frame');
stored = persistReviewAction(fs, stored, 'keep');
assert.strictEqual(stored.state.cursor, 1);
stored.lock.release();
assert.deepStrictEqual(listStoredSessions(fs, root, { sourceHash }).map(item => item.sessionId), ['sheet-test']);
const resumed = openStoredSession(fs, root, 'sheet-test');
assert.strictEqual(resumed.state.cursor, 1, 'a reopened session resumes at the exact persisted cursor');
assert.strictEqual(resumed.session.intakeEvidence.componentAudit.evidenceHash, componentAudit.evidenceHash, 'component membership evidence survives exact session recovery');
const stale = { ...resumed, session: { ...resumed.session, journal: [] } };
assert.throws(() => persistReviewAction(fs, stale, 'keep'), /changed after it was loaded/);
resumed.lock.release();
fs.writeFileSync(resumed.location.lock, JSON.stringify({ pid: 999999, identity: 'sheet-test' }));
const recoveredAfterCrash = openStoredSession(fs, root, 'sheet-test', { isProcessAlive: () => { const error = new Error('missing'); error.code = 'ESRCH'; throw error; } });
assert.strictEqual(recoveredAfterCrash.state.cursor, 1, 'a dead-process lock is reclaimed after crash or power loss'); recoveredAfterCrash.lock.release();
const snapshot = fs.readFileSync(resumed.location.source); snapshot[40] ^= 1; fs.writeFileSync(resumed.location.source, snapshot);
assert.throws(() => openStoredSession(fs, root, 'sheet-test', { readOnly: true }), /failed its hash check/);
assert.throws(() => createStoredSession(fs, root, source, proposal, { sessionId: '../escape' }), /unsupported characters/);
assert.throws(() => createStoredSession(fs, root, source, proposal, { sessionId: 'wrong-evidence', intakeEvidence: { sourceHash: 'f'.repeat(64) }, extractedFrames: extracted }), /different source bytes/);

console.log('SFF sprite-sheet sessions persist exact progress, reject concurrent edits, stale writers, changed snapshots, and unsafe paths');
