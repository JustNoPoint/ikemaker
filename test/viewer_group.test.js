'use strict';
const assert = require('assert');
const { configureViewerTopology, preferredViewerColumn, trackViewerPanel, revealInViewerGroup, reserveViewerColumns, releaseViewerColumns, resetViewerGroupForTests } = require('../src/viewer_group');

resetViewerGroupForTests();
assert.strictEqual(preferredViewerColumn(1), 1);
assert.strictEqual(preferredViewerColumn(-1), -2, 'a first visual viewer must open beside the active text group');
let changed, revealed;
const panel = { viewColumn: 2, onDidChangeViewState(callback) { changed = callback; }, onDidDispose() {}, reveal(column, preserveFocus) { revealed = { column, preserveFocus }; } };
trackViewerPanel(panel);
assert.strictEqual(preferredViewerColumn(1), 2);
assert.strictEqual(preferredViewerColumn(-2, 2), -2);
panel.active=true;panel.viewColumn=3;changed({ webviewPanel: panel });
assert.strictEqual(preferredViewerColumn(1), 3);
revealInViewerGroup({ viewColumn: undefined, reveal(column, preserveFocus) { revealed = { column, preserveFocus }; } }, true, 1);
assert.deepStrictEqual(revealed, { column: 3, preserveFocus: true });
resetViewerGroupForTests();
let dispose;
const finalPanel = { viewColumn: 4, onDidChangeViewState() {}, onDidDispose(callback) { dispose = callback; } };
trackViewerPanel(finalPanel);
dispose();
assert.strictEqual(preferredViewerColumn(1), 1);
let disposeActive;
trackViewerPanel({viewColumn:2,onDidDispose(){}});
trackViewerPanel({viewColumn:4,active:true,onDidDispose(callback){disposeActive=callback;}});
disposeActive();assert.strictEqual(preferredViewerColumn(1),2,'closing the active viewer must not retain its dead group as the preferred destination');
resetViewerGroupForTests();
let activateFirst, activateSecond, closeSecond;
const first={viewColumn:2,active:true,onDidChangeViewState(fn){activateFirst=fn;},onDidDispose(){}};
const second={viewColumn:4,active:false,onDidChangeViewState(fn){activateSecond=fn;},onDidDispose(fn){closeSecond=fn;}};
trackViewerPanel(first);trackViewerPanel(second);
assert.strictEqual(preferredViewerColumn(1),2,'A background restored tab must not steal the destination');
activateSecond({webviewPanel:second});assert.strictEqual(preferredViewerColumn(1),2);
second.active=true;second.viewColumn=5;activateSecond({webviewPanel:second});
assert.strictEqual(preferredViewerColumn(1),5,'Dragging and activating a viewer updates the destination');
let existingReveal;
revealInViewerGroup({viewColumn:3,reveal(column){existingReveal=column;}});
assert.strictEqual(existingReveal,3,'Reopening a moved viewer preserves its chosen group');
closeSecond();assert.strictEqual(preferredViewerColumn(1),2);
resetViewerGroupForTests();
let reservedReveal;
const misplaced={viewColumn:1,active:true,onDidChangeViewState(){},onDidDispose(){},reveal(target,preserveFocus){reservedReveal={target,preserveFocus};this.viewColumn=target;}};
trackViewerPanel(misplaced);
assert.strictEqual(preferredViewerColumn(1),1);
assert.strictEqual(reserveViewerColumns('text-editor',[1,2]),1,'reserving the text layout evacuates an already-open managed viewer');
assert.deepStrictEqual(reservedReveal,{target:-2,preserveFocus:true});
assert.strictEqual(preferredViewerColumn(1),-2,'new viewers never target either reserved text-editor group');
releaseViewerColumns('text-editor');
assert.strictEqual(preferredViewerColumn(1),1,'closing the text companion releases its exclusive groups');
resetViewerGroupForTests();
reserveViewerColumns('text-editor',[1,2]);let restoredReveal;
trackViewerPanel({viewColumn:1,onDidDispose(){},reveal(target,preserveFocus){restoredReveal={target,preserveFocus};this.viewColumn=target;}});
assert.deepStrictEqual(restoredReveal,{target:-2,preserveFocus:true},'a restored viewer is immediately removed from the text-only group');
let reopenedReveal;
revealInViewerGroup({viewColumn:2,reveal(target,preserveFocus){reopenedReveal={target,preserveFocus};}},false,1);
assert.deepStrictEqual(reopenedReveal,{target:-2,preserveFocus:false},'focusing an older viewer cannot put it back into a reserved text group');
resetViewerGroupForTests();
const liveHeader={viewColumn:1},liveNative={viewColumn:2};
reserveViewerColumns('text-editor',[liveHeader,liveNative]);
assert.strictEqual(preferredViewerColumn(1),-2);
liveHeader.viewColumn=3;liveNative.viewColumn=4;
assert.strictEqual(preferredViewerColumn(3),-2,'live group reservations follow layout reindexing instead of stale numeric columns');
assert.strictEqual(preferredViewerColumn(1),1,'the old column is released after live group reindexing');
resetViewerGroupForTests();
const reservedWindowGroup={viewColumn:1,tabs:[]},floatingViewerGroup={viewColumn:1,tabs:[]};let activeGroup=floatingViewerGroup;
configureViewerTopology(()=>({all:[reservedWindowGroup,floatingViewerGroup],active:activeGroup}));
reserveViewerColumns('text-editor',[reservedWindowGroup]);
const floatingPanel={viewColumn:1,active:true,title:'Floating viewer',onDidChangeViewState(){},onDidDispose(){},reveal(){throw new Error('A distinct floating group with the same column number must not be rehomed.');}};
trackViewerPanel(floatingPanel);
assert.strictEqual(preferredViewerColumn(-1),1,'live group identity preserves a deliberate floating/new-window viewer');
resetViewerGroupForTests();
reserveViewerColumns('text-editor',[1]);let asyncReveals=0,asyncState;
const restoring={viewColumn:1,active:false,onDidChangeViewState(listener){asyncState=listener;},onDidDispose(){},reveal(){asyncReveals+=1;}};
trackViewerPanel(restoring);reserveViewerColumns('text-editor',[1]);reserveViewerColumns('text-editor',[1]);
assert.strictEqual(asyncReveals,1,'restore-time tab storms cannot issue a second relocation before the first one settles');
restoring.viewColumn=3;asyncState({webviewPanel:restoring});reserveViewerColumns('text-editor',[1]);
assert.strictEqual(asyncReveals,1,'a safe view-state acknowledgement clears relocation without another move');
resetViewerGroupForTests();
console.log('Shared visual viewer group tests passed');
