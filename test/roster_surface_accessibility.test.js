'use strict';
const assert=require('assert'),Module=require('module'),original=Module._load;
Module._load=function(request,parent,main){if(request==='vscode')return{window:{},workspace:{},commands:{},Uri:{file:fsPath=>({fsPath})},ViewColumn:{}};return original.call(this,request,parent,main);};
const roster=require('../src/select_def_workspace');Module._load=original;

assert.strictEqual(roster.rosterTabTarget(0,'ArrowLeft',4),3);
assert.strictEqual(roster.rosterTabTarget(3,'ArrowRight',4),0);
assert.strictEqual(roster.rosterTabTarget(2,'Home',4),0);
assert.strictEqual(roster.rosterTabTarget(1,'End',4),3);
assert.strictEqual(roster.rosterCollectionTarget(0,'ArrowLeft',3),0,'record navigation does not wrap past the first record');
assert.strictEqual(roster.rosterCollectionTarget(2,'ArrowRight',3),2,'record navigation does not wrap past the last record');
assert.strictEqual(roster.rosterCollectionTarget(1,'Home',3),0);

let state=roster.rosterSurfaceAvailability({count:0,motifReady:false});
assert(state.rosterPrev.disabled&&/No roster records/.test(state.rosterPrev.reason));
assert(state.rosterRange.disabled&&/No roster records/.test(state.rosterRange.reason));
assert(state.rosterEditPreferred.disabled&&/Choose a roster record/.test(state.rosterEditPreferred.reason));
assert(state.zoomIn.disabled&&/motif/.test(state.zoomIn.reason));
state=roster.rosterSurfaceAvailability({count:1,index:0,selected:true,motifReady:true,dirty:false});
assert(state.rosterRange.disabled&&/Only one/.test(state.rosterRange.reason));
assert(!state.rosterSelect.disabled&&!state.rosterEditPreferred.disabled);
assert(state.applyOrder.disabled&&/Reorder/.test(state.applyOrder.reason));
state=roster.rosterSurfaceAvailability({count:3,index:1,motifReady:true,dirty:true,page:1,pageCount:3});
assert(!state.rosterPrev.disabled&&!state.rosterNext.disabled&&!state.rosterRange.disabled&&!state.applyOrder.disabled);
assert(!state.pagePrev.disabled&&!state.pageNext.disabled);
state=roster.rosterSurfaceAvailability({count:3,index:2,dirty:true,conflict:true,draftError:'disk failed',busy:false,zoom:4,page:2,pageCount:3});
assert(state.applyOrder.disabled&&/Discard/.test(state.applyOrder.reason));
assert(!state.discardConflict.disabled&&!state.retryDraft.disabled);
assert(state.rosterNext.disabled&&/last roster record/.test(state.rosterNext.reason));
assert(state.zoomIn.disabled&&/maximum zoom/.test(state.zoomIn.reason));
state=roster.rosterSurfaceAvailability({dirty:true,busy:true});
assert(state.applyOrder.disabled&&/finish storing/.test(state.applyOrder.reason));
assert(state.discardOrder.disabled&&/finish storing/.test(state.discardOrder.reason));

