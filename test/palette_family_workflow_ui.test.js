'use strict';

const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { createPaletteWorkspaceSession, revisePaletteWorkspaceSession } = require('../src/palette_workspace_session');
const { sourceHtml } = require('../src/palette_workspace_view');

const target = { filename: path.resolve('family-ui.sff'), byteHash: 'a'.repeat(64), byteLength: 1000 };
let session = createPaletteWorkspaceSession({ sessionId: 'family-ui', target, plan: { filename: path.resolve('family-ui.palette-plan.json'), exists: false, byteHash: 'b'.repeat(64), byteLength: 0 } });
const retained = { schema: 'ikemaker.palette-family-color-assignment', version: 1, readOnly: true, activeSffChanged: false, committed: false, stateHash: 'c'.repeat(64) };
session = revisePaletteWorkspaceSession(session, session.revision, { family: { status: 'browsing', config: { scope: 'both', namedMappingIds: ['remap-family'], aliasDecisions: { 2: 'materialize-independent' } }, assignment: retained } });
assert.strictEqual(session.family.status, 'browsing');
assert.deepStrictEqual(session.family.config.namedMappingIds, ['remap-family']);
assert.strictEqual(session.family.assignment.stateHash, retained.stateHash, 'retained Quick Browse state stays in the canonical Palette Workspace session');

const html = sourceHtml({ session, palettes: [] });
const inline = html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert(inline);
assert.doesNotThrow(() => new vm.Script(inline, { filename: 'palette-family-workflow-inline.js' }));
assert.match(html, /family-dock/);
assert.match(html, /Quick Browse Colors/);
assert.match(html, /type="color"/);
assert.match(html, /Hex RGBA/);
assert.match(html, /RGBA/);
assert.match(html, /HSL/);
assert.match(html, /familyExplicitRanges/);
assert.match(html, /Explicit directed RemapPal ranges/);
assert.match(html, /inherited-source|sourceBadge|family-status/);
assert.match(html, /unresolved/);
for (const action of ['familyBack', 'familySkip', 'familyCopyMaster', 'familyCopyPrevious', 'familyUndo', 'familyApplyNext', 'familyEscape', 'familyFinish', 'familyScope', 'familySetBase', 'familyBatchScope']) assert.match(html, new RegExp(action));
assert.match(html, /event\.key==='Enter'/);
assert.match(html, /event\.key==='Escape'/);
assert.match(html, /draft retained/);
assert.match(html, /Finish created this atomic summary only/);
assert.match(html, /No SFF, palette metadata, sprite, or source image was written/);
assert.match(html, /aria-label="Quick Browse palette family controls"/);
assert.match(html, /RGBA channel/);
assert.match(html, /aria-live="polite"/);
assert.match(html, /:focus-visible/);
assert.match(html, /prefers-reduced-motion:reduce/);
assert.match(html, /max-width:560px/, 'the family browser stays a narrow dock rather than a full-page form');
assert.doesNotMatch(html, /family-actions[^}]*width:100%/);
for (const label of ['Build Candidate', 'Compare', 'Adopt', 'Undo Adoption', 'Recover']) assert.match(html, new RegExp(label));
for (const action of ['familyBuildCandidate', 'familyCompareCandidate', 'familyAdoptCandidate', 'familyUndoAdoption', 'familyRecoverAdoption']) assert.match(html, new RegExp(action));
for (const action of ['familyAttachTemplate', 'familyTemplateDecisions', 'familySyncReview', 'familyRecoverUnindexed']) assert.match(html, new RegExp(action));
for (const action of ['familyPrepareReverseSync', 'familyBuildReverseSync', 'familyCompareReverseSync', 'familyAdoptReverseSync', 'familyUndoReverseSync', 'familyRecoverReverseSync', 'familyConflictAction']) assert.match(html, new RegExp(action));
assert.match(html, /Project → Images/);
assert.match(html, /Images → Project/);
assert.match(html, /Index RGB Image/);
for (const label of ['Resolve to index', 'Replace', 'Add color', 'Workshop', 'Cancel', 'Previous occurrence', 'Next occurrence', 'Zoom out', 'Zoom in']) assert.match(html, new RegExp(label));
assert.match(html, /static-outline hatch/);
assert.match(html, /No nearest-color match is offered/);
assert.match(html, /Ask before project updates on future syncs/);

const controller = fs.readFileSync(path.join(__dirname, '..', 'src', 'palette_workspace_controller.js'), 'utf8');
assert.match(controller, /familyPlanner\.planPaletteFamily/);
assert.match(controller, /familyTopology\.createCandidate/);
assert.match(controller, /familyTopology\.verifyCandidate/);
assert.match(controller, /familyColors\.assertBindings/);
assert.match(controller, /String\(message\.stateHash\|\|''\)!==assignment\.stateHash/, 'every browse message uses stale-state compare-and-swap evidence');
assert.match(controller, /familyColors\.finish\(assignment\)/);
assert.match(controller, /status='summary'/);
assert.match(controller, /activeSffChanged:false/);
assert.match(controller, /familyWriter\.buildCandidate/);
assert.match(controller, /familyWriter\.verifyCandidate/);
assert.match(controller, /familyWriter\.adopt/);
assert.match(controller, /reverseSync\.buildCandidate/);
assert.match(controller, /reverseSync\.verifyCandidate/);
assert.match(controller, /reverseSync\.adopt/);
assert.match(controller, /paletteReferenceAudit\.auditPaletteReferences/);
assert.match(controller, /Dynamic or free-form palette reference requires manual review/);
assert.match(controller, /expectedVerificationHash:output\.verification\.verificationHash/);
assert.match(controller, /error\.recoveryRequired\?'recovery-needed':'rolled-back'/);
assert.strictEqual((controller.match(/if\(action==='familyStart'\)/g) || []).length, 1, 'the canonical controller has one family workflow owner');
assert.strictEqual((controller.match(/if\(action==='familyAdoptCandidate'\)/g) || []).length, 1, 'the canonical controller has one adoption route');
assert.doesNotMatch(controller, /family(?:Start|Edit|ApplyNext|Finish)[\s\S]{0,350}(transactionalWrite|writeFileSync|prepareSffHandoff)/, 'family browser routes remain candidate-only and non-writing');

console.log('Palette-family canonical compact UI, keyboard, accessibility, retained session, stale binding, and no-write source tests passed');
