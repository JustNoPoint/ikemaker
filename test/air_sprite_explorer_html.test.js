'use strict';
const assert = require('assert');
const Module = require('module');
const path = require('path');
const vm = require('vm');
const originalLoad = Module._load;
Module._load = function patched(request, parent, isMain) {
  if (request === 'vscode') return {};
  if (request === './air_viewer' && /air_docking_workspace\.js$/.test(parent?.filename || '')) return { parseAir: () => [], inferCharacterFiles: () => ({}), collisionRuntimeOptions: () => ({}), collisionRuntimeDraftEntries: () => [] };
  return originalLoad.call(this, request, parent, isMain);
};
const { html } = require('../src/air_docking_workspace');
Module._load = originalLoad;
const output = html({ airPath: path.resolve('/char/main.air'), sourceFingerprint: 'A'.repeat(64), actions: [{ number: 0, frames: [], line: 1 }], references: { available: false, items: [], occurrences: [] }, initialView: 'sprites', initialCollisionMode: 'inspect', initialTransform: {}, initialProperty: {}, initialAssistance: {}, spriteExplorer: { available: true, reason: '', groups: [0], omitted: 0, sprites: [{ physicalIndex: 0, group: 0, number: 0, width: 10, height: 20, customName: '', note: '', flags: [] }] } });
assert(output.includes('SFF Sprite Explorer') && output.includes('Create New Animation…') && output.includes('Append to Current Action…'));
assert(output.includes('spriteGroupFilter') && output.includes('spriteFilter') && output.includes('spriteReviewFilter'));
assert(output.includes('All review statuses') && output.includes('spriteShowThumbs') && output.includes('spriteThumbSize'));
assert(output.includes('spriteExplorerThumbs') && output.includes("type:'spriteMutation'"));
const script = /<script[^>]*>([\s\S]*?)<\/script>/.exec(output)?.[1];
assert(script, 'browser script exists');
new vm.Script(script);
console.log('AIR SFF Sprite Explorer HTML tests passed');
