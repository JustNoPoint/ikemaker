'use strict';

const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { PaletteScratchService, evidence } = require('../src/palette_scratch_service');
const scratch = require('../src/palette_scratch_document');

const root=fs.mkdtempSync(path.join(os.tmpdir(),'ikemaker-palette-scratch-')),store={value:{},get(key,fallback){return this.value[key]||fallback},update(key,value){this.value[key]=JSON.parse(JSON.stringify(value));return Promise.resolve()}},service=new PaletteScratchService(store);
const created=service.create({name:'Accessible test palette'}),id=created.document.draftId;
assert.strictEqual(created.document.colors.length,256);
assert.strictEqual(created.dirty,true,'a new unsaved palette must not be silently treated as saved');
assert(service.list().some(item=>item.draftId===id&&item.dirty),'an unsaved palette remains reachable from retained drafts');
assert.throws(()=>service.color(id,created.revision,0,[1,2,3,4]),/index 0 is locked/i);
let changed=service.color(id,created.revision,7,[1,2,3,4]);
assert.deepStrictEqual(changed.document.colors[7],[1,2,3,4]);
assert.strictEqual(changed.dirty,true);
changed=service.undo(id,changed.revision);
assert.deepStrictEqual(changed.document.colors[7],[0,0,0,255]);
assert.strictEqual(changed.redo.length,1,'Undo retains one exact lossless palette-document Redo checkpoint');
changed=service.redo(id,changed.revision);
assert.deepStrictEqual(changed.document.colors[7],[1,2,3,4],'Redo restores the exact undone RGBA edit');
changed=service.undo(id,changed.revision);
changed=service.color(id,changed.revision,7,[4,3,2,255]);
assert.strictEqual(changed.redo.length,0,'a new palette-document edit invalidates the prior Redo branch');
const filename=path.join(root,'test.ikpalette.json'),saved=service.save(id,filename);
assert.strictEqual(saved.dirty,false);
assert.strictEqual(scratch.parseScratchPaletteDocument(fs.readFileSync(filename,'utf8')).semanticHash,saved.document.semanticHash);
const restoredService=new PaletteScratchService(store),restored=restoredService.snapshot(id);
assert.strictEqual(restored.document.semanticHash,saved.document.semanticHash,'retained scratch state survives service recreation');
const dirty=restoredService.color(id,restored.revision,8,[8,7,6,255]),reopenedService=new PaletteScratchService(store),reopened=reopenedService.openFile(filename);
assert.strictEqual(reopened.document.semanticHash,dirty.document.semanticHash,'unsaved retained edits reopen when the exact saved destination is unchanged');
assert.strictEqual(reopened.dirty,true);
fs.writeFileSync(filename,'externally changed');
assert.throws(()=>reopenedService.save(id,filename),/changed after it was loaded/i,'external writes block overwrite');
const replacement=path.join(root,'replace.ikpalette.json');
fs.writeFileSync(replacement,'first reviewed destination');
const reviewed=evidence(replacement);
fs.writeFileSync(replacement,'changed after Save As picker');
assert.throws(()=>reopenedService.save(id,replacement,{replace:true,replaceEvidence:reviewed}),/changed after it was reviewed/i,'Save As never overwrites a destination that changed after review');
assert.strictEqual(fs.readFileSync(replacement,'utf8'),'changed after Save As picker');
fs.rmSync(root,{recursive:true,force:true});
console.log('Palette scratch service persistence, lock, undo/redo, verified save, and CAS tests passed');
