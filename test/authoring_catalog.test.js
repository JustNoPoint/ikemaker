'use strict';
const assert = require('assert');
const catalog = require('../src/authoring_catalog');

const items = catalog.allItems();
assert(items.length > 35, 'catalog includes structures, recipes, sections, and examples');
assert.strictEqual(new Set(items.map((item) => item.id)).size, items.length, 'catalog IDs are stable and unique');
assert(catalog.STANDARD_RECIPES.every((item) => item.source === 'IKEMEN Standard' && item.compatibility === 'universal'));
assert.strictEqual(catalog.recipes().some(item=>item.nightlyString),false,'ordinary/1.0 recipe views omit Nightly strings completely');
assert(catalog.recipes({nightlyStringsEnabled:true}).some(item=>item.id==='nightly.recipe.string-map'),'verified Nightly views can expose string recipes');
assert(!catalog.recipes({nightlyStringsEnabled:true}).some(item=>item.id==='nightly.recipe.dynamic-command'),'runtime strings alone do not expose a recipe for an independently gated command feature');
const commandRecipes=catalog.recipes({nightlyStringsEnabled:true,capabilities:{enabledCapabilities:['command.nightly-expressions']}});
assert(commandRecipes.some(item=>item.id==='nightly.recipe.dynamic-command'),'the exact command-expression capability reveals its recipe');
assert(catalog.itemById('nightly.recipe.dynamic-command.section.command-local').capabilityId==='command.nightly-expressions','recipe sections inherit the host-rechecked capability requirement');
assert.deepStrictEqual(catalog.EXAMPLE_PACKS.map((item) => item.id), ['example.sf6', 'example.ds', 'example.ds4', 'example.hdbz']);
assert(catalog.search('projectile cleanup').some((item) => /projectile|cleanup/i.test(`${item.label} ${item.detail} ${item.family}`)));
assert(catalog.itemById('standard.recipe.normal.basic.section.attack').snippet.includes('hitDef'));
const slp = catalog.itemById('project.sf6.recipe.normal.slp');
assert(slp && slp.source === 'Project: SF6 Template — JustNoPoint');
assert.strictEqual(slp.sections.length, 8);
assert(slp.dependencies.some((item) => item.includes('corner-recoil')));
assert.strictEqual(catalog.itemById('project.sf6.recipe.normal.slp.section.state').symbol, 'StateDef 200');
assert(catalog.itemById('project.sf6.recipe.normal.slp.section.sharedLightPunch').referenceOnly);
assert.deepStrictEqual(slp.modes.map((mode) => mode.id), ['configure', 'extend', 'override']);
assert.strictEqual(slp.ownershipLevels.length, 4);
const override = catalog.itemById('project.sf6.recipe.normal.characterOverride');
assert(override.referenceOnly && override.validationChecklist.length === 10);
assert(catalog.itemById('project.sf6.recipe.normal.slp.section.state').referenceOnly, 'common state is not offered as ordinary character insertion');
console.log('Authoring catalog has unique provenance-aware structures, modular recipes, and four bundled example-pack foundations');
