'use strict';
const assert = require('assert');
const path = require('path');
const authority = require('../src/map_registry_authority');
const root = path.resolve('C:/game/chars/Ryu'), def = path.join(root, 'Ryu.def'), source = path.join(root, 'Ryu.zss');
const occurrence = { name: 'Player.Health', filename: source, language: 'zss', line: 4, character: 2, access: 'read', source: 'map(Player.Health)', notes: [] };
const registry = { root, def, projectId: 'sf6', indexedFiles: [source], entries: [{ name: 'Player.Health', occurrences: [occurrence] }] };
const row = authority.occurrenceReferences(registry)[0], entry = authority.entryReference(registry.entries[0], registry);
assert(authority.validEntryReference(entry));
assert(authority.validOccurrenceReference(row.reference));
assert(Object.isFrozen(row.reference));
const shifted = { ...registry, entries: [{ ...registry.entries[0], occurrences: [{ ...occurrence, line: 99 }] }] };
assert(authority.resolveOccurrence(shifted, row.reference), 'unrelated line shifts preserve exact semantic occurrence identity');
const changed = { ...registry, entries: [{ ...registry.entries[0], occurrences: [{ ...occurrence, source: 'map(Player.Health) + 1' }] }] };
assert.equal(authority.resolveOccurrence(changed, row.reference), null, 'changed raw source fails closed');
const duplicated = { ...registry, entries: [{ ...registry.entries[0], occurrences: [occurrence, { ...occurrence, line: 7 }] }] };
assert.equal(authority.resolveOccurrence(duplicated, row.reference), null, 'changed exact match count fails closed');
assert(!authority.validOccurrenceReference({ ...row.reference, line: 4 }));
assert(!authority.validOccurrenceReference(Object.assign(Object.create(null), row.reference)));
console.log('Maps Registry M1 entry/occurrence identity, relocation, ambiguity, and strict validation tests passed');
